-- Сделка из проекта больше не хранит копию его названия: поле title остаётся
-- пустым, а заголовок собирается из связи (см. dealDisplayTitle в lib/crm/deal).
-- Чистим ранее вшитые копии — иначе они продолжат показывать название проекта
-- на момент создания сделки, расходясь с карточкой проекта.
UPDATE "deals"
SET "title" = NULL
WHERE "sourceProjectId" IS NOT NULL
  AND "title" LIKE 'По проекту: %';
