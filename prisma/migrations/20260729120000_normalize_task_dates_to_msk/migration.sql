-- Задачи «на весь день» раньше хранились как UTC-полночь (плавающая дата):
-- 2026-07-29T00:00:00.000Z … 2026-07-29T23:59:59.999Z. «Просрочено» и «сегодня»
-- при этом считались против реального времени, поэтому срок «сегодня» наступал
-- только в 03:00 следующих суток по Москве.
--
-- Приводим к единому инварианту: в базе лежат реальные моменты, задача на весь
-- день занимает московские сутки целиком (00:00:00.000 … 23:59:59.999 МСК).
-- SQLite хранит DateTime как число миллисекунд, поэтому сдвигаем на 3 часа.
UPDATE "tasks"
SET "startAt" = "startAt" - 10800000,
    "endAt" = "endAt" - 10800000
WHERE "allDay" = 1;
